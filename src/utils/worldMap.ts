export function getWorldMapCoordinate(regionCode: string): WorldMapCoordinate | null {
  return WORLD_MAP_COORDINATES[regionCode.trim().toUpperCase()] ?? null
}

export function getWorldMapMarkers(nodes: readonly NodeData[]): WorldMapMarker[] {
  const grouped = new Map<string, { mapName: string, name: string, coordinate: WorldMapCoordinate, nodes: NodeData[] }>()

  nodes.forEach((node) => {
    const region = node.region?.trim()
    if (!region)
      return

    const regionInfo = getRegionByAlias(region)
    const code = (regionInfo?.code ?? getRegionCode(region)).trim().toUpperCase()
    const codeRegionInfo = getRegionByAlias(code)
    const displayRegion = regionInfo ?? codeRegionInfo
    const coordinate = getWorldMapCoordinate(code)
    if (!coordinate)
      return

    const existing = grouped.get(code)
    if (existing) {
      existing.nodes.push(node)
      return
    }

    grouped.set(code, {
      mapName: WORLD_MAP_NAME_OVERRIDES[code] ?? displayRegion?.en ?? region,
      name: displayRegion?.zh ?? getRegionDisplayName(region),
      coordinate,
      nodes: [node],
    })
  })

  return [...grouped.entries()]
    .map(([code, region]) => ({
      code,
      mapName: region.mapName,
      name: region.name,
      coordinate: region.coordinate,
      count: region.nodes.length,
      onlineCount: region.nodes.filter(node => node.online).length,
      nodes: region.nodes,
    }))
    .sort((left, right) => right.count - left.count || left.name.localeCompare(right.name, 'zh-CN'))
}
